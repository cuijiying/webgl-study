'use strict';
/**
 * 3D "F" 字母几何数据，供 3D / 光照 / 动画等 demo 复用。
 * 提供：positions(位置)、normals(法线)、colors(逐顶点颜色)。
 * 坐标范围大致 x:[0,100] y:[0,150] z:[0,30]，原点在左上前方。
 */
const Geometry = (() => {
  // 96 个顶点（16 个面 × 2 三角形 × 3 顶点），每顶点 3 个 float
  const positions = new Float32Array([
    // 左竖 正面
    0,0,0,  0,150,0,  30,0,0,   0,150,0, 30,150,0, 30,0,0,
    // 上横 正面
    30,0,0, 30,30,0, 100,0,0,   30,30,0, 100,30,0, 100,0,0,
    // 中横 正面
    30,60,0, 30,90,0, 67,60,0,  30,90,0, 67,90,0, 67,60,0,
    // 左竖 背面
    0,0,30, 30,0,30, 0,150,30,  0,150,30, 30,0,30, 30,150,30,
    // 上横 背面
    30,0,30, 100,0,30, 30,30,30,  30,30,30, 100,0,30, 100,30,30,
    // 中横 背面
    30,60,30, 67,60,30, 30,90,30,  30,90,30, 67,60,30, 67,90,30,
    // 顶面
    0,0,0, 100,0,0, 100,0,30,  0,0,0, 100,0,30, 0,0,30,
    // 上横 右侧
    100,0,0, 100,30,0, 100,30,30,  100,0,0, 100,30,30, 100,0,30,
    // 上横 底面
    30,30,0, 30,30,30, 100,30,30,  30,30,0, 100,30,30, 100,30,0,
    // 上横与中横之间 左侧
    30,30,0, 30,60,30, 30,30,30,  30,30,0, 30,60,0, 30,60,30,
    // 中横 顶面
    30,60,0, 67,60,30, 30,60,30,  30,60,0, 67,60,0, 67,60,30,
    // 中横 右侧
    67,60,0, 67,90,30, 67,60,30,  67,60,0, 67,90,0, 67,90,30,
    // 中横 底面
    30,90,0, 30,90,30, 67,90,30,  30,90,0, 67,90,30, 67,90,0,
    // 下半竖 右侧
    30,90,0, 30,150,30, 30,90,30,  30,90,0, 30,150,0, 30,150,30,
    // 底面
    0,150,0, 0,150,30, 30,150,30,  0,150,0, 30,150,30, 30,150,0,
    // 左侧面
    0,0,0, 0,0,30, 0,150,30,  0,0,0, 0,150,30, 0,150,0,
  ]);

  // 每个面 6 个顶点共用一个法线
  const faceNormals = [
    [0,0,1],[0,0,1],[0,0,1],       // 三个正面
    [0,0,-1],[0,0,-1],[0,0,-1],    // 三个背面
    [0,1,0],   // 顶面
    [1,0,0],   // 上横右
    [0,-1,0],  // 上横底
    [1,0,0],   // 之间左
    [0,1,0],   // 中横顶
    [1,0,0],   // 中横右
    [0,-1,0],  // 中横底
    [1,0,0],   // 下半竖右
    [0,-1,0],  // 底面
    [-1,0,0],  // 左侧
  ];
  const normals = new Float32Array(96 * 3);
  for (let f = 0; f < 16; f++) {
    const n = faceNormals[f];
    for (let v = 0; v < 6; v++) {
      const idx = (f * 6 + v) * 3;
      normals[idx] = n[0]; normals[idx+1] = n[1]; normals[idx+2] = n[2];
    }
  }

  // 逐面着色，便于在无光照时区分各个面
  const facePalette = [
    [0.78,0.27,0.47],[0.78,0.27,0.47],[0.78,0.27,0.47],  // 正面
    [0.5,0.27,0.78],[0.5,0.27,0.78],[0.5,0.27,0.78],      // 背面
    [0.27,0.6,0.78],   // 顶
    [0.27,0.78,0.6],   // 上横右
    [0.78,0.6,0.27],   // 上横底
    [0.6,0.78,0.27],   // 之间左
    [0.27,0.78,0.4],   // 中横顶
    [0.4,0.27,0.78],   // 中横右
    [0.78,0.4,0.27],   // 中横底
    [0.27,0.5,0.78],   // 下半竖右
    [0.78,0.78,0.27],  // 底
    [0.5,0.5,0.6],     // 左侧
  ];
  const colors = new Float32Array(96 * 3);
  for (let f = 0; f < 16; f++) {
    const c = facePalette[f];
    for (let v = 0; v < 6; v++) {
      const idx = (f * 6 + v) * 3;
      colors[idx] = c[0]; colors[idx+1] = c[1]; colors[idx+2] = c[2];
    }
  }

  const vertexCount = 96;

  /**
   * 生成交错的顶点数据 [x,y,z, r,g,b, nx,ny,nz] × 96。
   * 让 F 居中：减去中心点偏移 (50, 75, 15)。
   */
  function interleaved({ center = true } = {}) {
    const out = new Float32Array(vertexCount * 9);
    for (let i = 0; i < vertexCount; i++) {
      let x = positions[i*3], y = positions[i*3+1], z = positions[i*3+2];
      if (center) { x -= 50; y -= 75; z -= 15; }
      const o = i * 9;
      out[o] = x; out[o+1] = y; out[o+2] = z;
      out[o+3] = colors[i*3]; out[o+4] = colors[i*3+1]; out[o+5] = colors[i*3+2];
      out[o+6] = normals[i*3]; out[o+7] = normals[i*3+1]; out[o+8] = normals[i*3+2];
    }
    return out;
  }

  return { positions, normals, colors, vertexCount, interleaved };
})();
